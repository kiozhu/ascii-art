def block_render(text, fill='█', outline='█'):
    """
    Render text using filled block characters.
    fill/outline allow swapping solid blocks with half-blocks.
    """
    BLOCK = {k: [row.replace('█', fill) for row in v] for k, v in BLOCK_CHARS.items()}
    text = text.upper()
    lines = ['', '', '', '', '']
    for ch in text:
        rows = BLOCK.get(ch, BLOCK[' '])
        for i in range(5):
            lines[i] += rows[i] + ' '
    return '\n'.join(lines)


