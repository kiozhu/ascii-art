# ─── Render ────────────────────────────────────────────────────────────────
def block_art(text):
    """Render text as Unicode pixel art (5 rows)"""
    lines = ['', '', '', '', '']
    for c in text.upper():
        if c in PIXEL_FONT:
            for i in range(5):
                lines[i] += PIXEL_FONT[c][i]
        else:
            for i in range(5):
                lines[i] += '    '
    return '\n'.join(lines)


